"""De-Bruijn driver: certify concrete ground recursor computations
   (incl. 1+1=2) against db.mm1.  Checked by mm0-rs AND mm0-c."""
import subprocess, os
from db_cert import (Var, App, Lam, Const, TNAT, TZERO, TSUCC, TREC,
                     curry, pp, prove_norm, proof_nodes)

MM0   = "/home/bepis/prog/scientific-computing/mm0"
MM0RS = f"{MM0}/mm0-rs/target/release/mm0-rs"
MM0C  = f"{MM0}/mm0-c/mm0-c-np"
HERE  = os.path.dirname(os.path.abspath(__file__))

def num(n):                       # Church-free de-Bruijn numeral: succ^n zero
    t = TZERO
    for _ in range(n): t = App(TSUCC, t)
    return t

MOT = Lam(TNAT, TNAT)                              # motive  \_. Nat
SUC = Lam(TNAT, Lam(TNAT, App(TSUCC, Var(0))))     # step    \k.\ih. succ ih
# add = \m.\n. rec (\_.Nat) m (\k.\ih. succ ih) n   (recurse on n)
ADD = Lam(TNAT, Lam(TNAT, curry(TREC, [MOT, Var(1), SUC, Var(0)])))


def examples():
    return [
        ("rec_one:  rec (\\_.N) 0 (\\k ih. S ih) (S 0)  =>  1",
            curry(TREC, [MOT, TZERO, SUC, num(1)])),
        ("rec_two:  rec (\\_.N) 0 (\\k ih. S ih) (S S 0)  =>  2",
            curry(TREC, [MOT, TZERO, SUC, num(2)])),
        ("add 1 1  =>  2   (full: 2 outer betas + iota + inner betas)",
            App(App(ADD, num(1)), num(1))),
        ("add 2 1  =>  3",
            App(App(ADD, num(2)), num(1))),
    ]


def main():
    prelude = open(f"{HERE}/db.mm1").read()
    frag = ["-- AUTO-GENERATED by db_cert.py  (de-Bruijn ground computations)"]
    summary = []
    for i, (desc, e) in enumerate(examples()):
        nf, conv = prove_norm(e)
        conv = conv or "(deq_refl)"
        n = proof_nodes(conv)
        frag.append(f"-- {desc}   ({n} proof nodes)\n"
                    f"theorem db_{i}: $ deq cnil {pp(e)} {pp(nf)} $ =\n'{conv};\n")
        summary.append((desc, pp(nf), n))
    fragtext = "\n".join(frag)
    open(f"{HERE}/_gen_db.mm1", "w").write(fragtext)
    open("/tmp/cert_db.mm1", "w").write(prelude + "\n" + fragtext)

    print(fragtext[:1500] + ("\n... [truncated]" if len(fragtext) > 1500 else ""))
    print("=" * 66)
    for desc, nf, n in summary:
        print(f"  {n:4d} nodes   {desc}\n               => normal form: {nf}")
    print("  (our verifier: 1 de-refl each; shift/subst here are PROVEN, not builtin)")
    print("=" * 66)
    r = subprocess.run([MM0RS, "compile", "/tmp/cert_db.mm1", "/tmp/cert_db.mmb"],
                       capture_output=True, text=True)
    print("mm0-rs verify:", "OK (exit 0)" if r.returncode == 0 else "FAIL")
    if r.returncode != 0:
        print(r.stdout[-3000:]); print(r.stderr[-3000:]); return
    if os.path.exists(MM0C):
        rc = subprocess.run([MM0C, "/tmp/cert_db.mmb"]).returncode
        print("mm0-c  verify:", "OK (exit 0)" if rc == 0 else f"FAIL ({rc})")


main()
