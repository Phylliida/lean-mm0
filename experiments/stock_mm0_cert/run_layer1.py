"""Layer 1 driver: generate substitution certificates and check with mm0-rs."""
import subprocess, os
from cert import (Var, Const, App, Lam, Pi, emit_subst_theorem)

MM0   = "/home/bepis/prog/scientific-computing/mm0"
MM0RS = f"{MM0}/mm0-rs/target/release/mm0-rs"
MM0C  = "/home/bepis/prog/scientific-computing/mm0/mm0-c/mm0-c-np"
LEAN  = f"{MM0}/examples/lean.mm1"
HERE  = os.path.dirname(os.path.abspath(__file__))


def build_examples():
    f, C, a = Var("f"), Var("C"), Var("a")
    succ, zero = Const("nat_succ"), Const("nat_zero")
    exs = [
        ("app:  (f x)[a/x]",
            App(f, Var("x")), a, "x"),
        ("lam:  (\\y:b. f x)[a/x]",
            Lam("y", Var("b"), App(f, Var("x"))), a, "x"),
        ("Pi:   (C n -> C (succ n))[zero/n]   <- the iota-typing subst",
            Pi("d", App(C, Var("n")), App(C, App(succ, Var("n")))), zero, "n"),
    ]
    # deep spine  f (f (... (f x)))  depth 25  -> shows it scales linearly
    t = Var("x")
    for _ in range(25):
        t = App(f, t)
    exs.append(("deep: f^25 x  [a/x]   <- 25-deep nesting, generated", t, a, "x"))
    return exs


def main():
    frag = ["-- AUTO-GENERATED by cert.py  (Layer 1: substitution certificates)"]
    summary, total = [], 0
    for i, (desc, A, e, x) in enumerate(build_examples()):
        thm, nodes = emit_subst_theorem(f"gen_subst_{i}", A, e, x)
        frag.append(f"-- {desc}   ({nodes} proof nodes)\n{thm}")
        summary.append((desc, nodes)); total += nodes
    fragtext = "\n".join(frag)
    open(f"{HERE}/_gen_layer1.mm1", "w").write(fragtext)
    combined = open(LEAN).read() + "\n" + fragtext
    open("/tmp/cert_layer1.mm1", "w").write(combined)

    print(fragtext)
    print("=" * 64)
    for desc, nodes in summary:
        print(f"  {nodes:3d} nodes   {desc}")
    print(f"  {total:3d} nodes   TOTAL, all generated automatically "
          f"(our verifier: {len(summary)} x de-refl = {len(summary)})")
    print("=" * 64)

    r = subprocess.run([MM0RS, "compile", "/tmp/cert_layer1.mm1",
                        "/tmp/cert_layer1.mmb"], capture_output=True, text=True)
    print("mm0-rs verify:", "OK (exit 0)" if r.returncode == 0 else "FAIL")
    if r.returncode != 0:
        print(r.stdout[-2500:]); print(r.stderr[-2500:]); return
    if os.path.exists(MM0C):
        rc = subprocess.run([MM0C, "/tmp/cert_layer1.mmb"]).returncode
        print("mm0-c  verify:", "OK (exit 0)" if rc == 0 else f"FAIL ({rc})")


main()
