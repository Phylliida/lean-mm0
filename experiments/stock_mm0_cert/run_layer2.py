"""Layer 2 driver: generate beta-conversion certificates, check with mm0-rs."""
import subprocess, os
from cert import Var, App, Lam, Pi, pp
from cert_beta import prove_whnf, proof_nodes

MM0   = "/home/bepis/prog/scientific-computing/mm0"
MM0RS = f"{MM0}/mm0-rs/target/release/mm0-rs"
MM0C  = f"{MM0}/mm0-c/mm0-c-np"
LEAN  = f"{MM0}/examples/lean.mm1"
HERE  = os.path.dirname(os.path.abspath(__file__))

A, B, C = Var("A"), Var("B"), Var("C")
a, b, c = Var("a"), Var("b"), Var("c")


def lams(*pairs_then_body):
    *pairs, body = pairs_then_body
    for v, ty in reversed(pairs):
        body = Lam(v, ty, body)
    return body


def examples():
    exs = []
    # identity
    exs.append(("id:  (\\x:A. x) a = a",
        App(lams(("x", A), Var("x")), a),
        {"a": (A, "ha")}, "(A: expr) (ha: $ G |- a : A $)"))
    # K combinator
    exs.append(("K:   (\\p:A.\\q:B. p) a b = a",
        App(App(lams(("p", A), ("q", B), Var("p")), a), b),
        {"a": (A, "ha"), "b": (B, "hb")},
        "(A B: expr) (ha: $ G |- a : A $) (hb: $ G |- b : B $)"))
    # three binders deep
    exs.append(("K3:  (\\p:A.\\q:B.\\r:C. p) a b c = a",
        App(App(App(lams(("p", A), ("q", B), ("r", C), Var("p")), a), b), c),
        {"a": (A, "ha"), "b": (B, "hb"), "c": (C, "hc")},
        "(A B C: expr) (ha: $ G |- a : A $) (hb: $ G |- b : B $) (hc: $ G |- c : C $)"))
    # a redex whose contractum is itself a redex  ->  conv_trans chaining
    exs.append(("chain: (\\x:A. (\\y:A. y) x) a = a",
        App(lams(("x", A), App(lams(("y", A), Var("y")), Var("x"))), a),
        {"a": (A, "ha")}, "(A: expr) (ha: $ G |- a : A $)"))
    return exs


def main():
    frag = ["-- AUTO-GENERATED by cert_beta.py  (Layer 2: beta certificates)"]
    summary = []
    for i, (desc, term, env, binders) in enumerate(examples()):
        nf, conv = prove_whnf(term, [], env)
        n = proof_nodes(conv)
        stmt = f"G |= {pp(term)} = {pp(nf)}"
        frag.append(f"-- {desc}   ({n} proof nodes)\n"
                    f"theorem gen_beta_{i} {binders}:\n  $ {stmt} $ =\n'{conv};\n")
        summary.append((desc, n))
    fragtext = "\n".join(frag)
    open(f"{HERE}/_gen_layer2.mm1", "w").write(fragtext)
    open("/tmp/cert_layer2.mm1", "w").write(open(LEAN).read() + "\n" + fragtext)

    print(fragtext)
    print("=" * 64)
    for desc, n in summary:
        print(f"  {n:3d} nodes   {desc}")
    print(f"  (our verifier: {len(summary)} x de-refl = {len(summary)} nodes total)")
    print("=" * 64)

    r = subprocess.run([MM0RS, "compile", "/tmp/cert_layer2.mm1",
                        "/tmp/cert_layer2.mmb"], capture_output=True, text=True)
    print("mm0-rs verify:", "OK (exit 0)" if r.returncode == 0 else "FAIL")
    if r.returncode != 0:
        print(r.stdout[-3000:]); print(r.stderr[-3000:]); return
    if os.path.exists(MM0C):
        rc = subprocess.run([MM0C, "/tmp/cert_layer2.mmb"]).returncode
        print("mm0-c  verify:", "OK (exit 0)" if rc == 0 else f"FAIL ({rc})")


main()
