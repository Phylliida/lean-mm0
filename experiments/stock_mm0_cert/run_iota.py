"""Layer 3 driver (abstract algebra): certify nat recursor computations
   rec u C z s (succ^m zero) = ...   with C,z,s as hypotheses.  Checked by mm0-rs/mm0-c."""
import subprocess, os
from cert import Var, Const, App, Pi, Imp, NatRec, Sort, pp
from cert_iota import norm_rec, numeral, ZERO, SUCC
from cert_beta import proof_nodes

MM0   = "/home/bepis/prog/scientific-computing/mm0"
MM0RS = f"{MM0}/mm0-rs/target/release/mm0-rs"
MM0C  = f"{MM0}/mm0-c/mm0-c-np"
LEAN  = f"{MM0}/examples/lean.mm1"
HERE  = os.path.dirname(os.path.abspath(__file__))

U = "u"
C, z, s = Var("C"), Var("z"), Var("s")
ENV = {
    "C": (Imp(Const("nat"), Sort(U)), "hC"),
    "z": (App(C, ZERO), "hz"),
    "s": (Pi("n", Const("nat"),
             Imp(App(C, Var("n")), App(C, App(SUCC, Var("n"))))), "hs"),
}
HDR = ("(u: level) (C z s: expr)\n"
       "  (hC: $ nil |- C : nat -> Sort u $)\n"
       "  (hz: $ nil |- z : C @ nat_zero $)\n"
       "  (hs: $ nil |- s : A. n : nat, C @ n -> C @ (nat_succ @ n) $)")


def main():
    frag = ["-- AUTO-GENERATED by cert_iota.py  (Layer 3: recursor/iota certificates)"]
    summary = []
    for m in (1, 2, 3):
        major = numeral(m)
        lhs = App(App(App(App(NatRec(U), C), z), s), major)
        nf, conv, _ty = norm_rec(U, C, z, s, major, ("hC", "hz", "hs"), [], ENV)
        n = proof_nodes(conv)
        frag.append(f"-- rec on {m}={pp(major)}   ({n} proof nodes)\n"
                    f"theorem gen_iota_{m} {HDR}:\n"
                    f"  $ nil |= {pp(lhs)} = {pp(nf)} $ =\n'{conv};\n")
        summary.append((m, pp(major), n))
    fragtext = "\n".join(frag)
    open(f"{HERE}/_gen_iota.mm1", "w").write(fragtext)
    open("/tmp/cert_iota.mm1", "w").write(open(LEAN).read() + "\n" + fragtext)

    print(fragtext)
    print("=" * 64)
    for m, mj, n in summary:
        print(f"  m={m}: {n:3d} nodes   rec u C z s ({mj})")
    print("  (our verifier: 1 de-refl each)")
    print("=" * 64)
    r = subprocess.run([MM0RS, "compile", "/tmp/cert_iota.mm1",
                        "/tmp/cert_iota.mmb"], capture_output=True, text=True)
    print("mm0-rs verify:", "OK (exit 0)" if r.returncode == 0 else "FAIL")
    if r.returncode != 0:
        print(r.stdout[-3000:]); print(r.stderr[-3000:]); return
    if os.path.exists(MM0C):
        rc = subprocess.run([MM0C, "/tmp/cert_iota.mmb"]).returncode
        print("mm0-c  verify:", "OK (exit 0)" if rc == 0 else f"FAIL ({rc})")


main()
